// get_structure: 쪽/문단 구간이 거꾸로면 고칠 꼴을 알려 준다 (두글 추가 검증).
function validateGetStructure(args) {
  if (Array.isArray(args.pages) && args.pages.length === 2 && args.pages[1] < args.pages[0]) {
    throw invalidArgs(`pages [${args.pages[0]}, ${args.pages[1]}] is reversed — send [${args.pages[1]}, ${args.pages[0]}]`);
  }
  if (args.range && args.range.toPara < args.range.fromPara) {
    throw invalidArgs(`range fromPara ${args.range.fromPara} > toPara ${args.range.toPara} — the range is inclusive and must not be reversed`);
  }
}

